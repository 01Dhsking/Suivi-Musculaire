import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';
const entry = { recorded_at: '2026-10-20T12:00:00.000Z', weight: 81.4, waist: 92, fat: 24.5, muscle: 34.2, source: 'Test automatique', note: 'Donnée de test, supprimée après vérification.' };
test('API: validation, CRUD, transactional import and protection against foreign origins', async ({ request, baseURL }) => {
  const headers = { Origin: baseURL! };
  const createdIds: string[] = [];
  let phaseId: string | undefined;
  const original = await (await request.get('/api/tracker')).json();
  try {
    expect((await request.post('/api/measurements',{headers,data:{...entry,weight:-1}})).status()).toBe(400);
    expect((await request.post('/api/measurements',{headers:{Origin:'http://external.invalid'},data:entry})).status()).toBe(403);
    const created = await request.post('/api/measurements',{headers,data:entry});
    expect(created.status()).toBe(201);
    const m = await created.json(); createdIds.push(m.id);
    expect((await request.put('/api/measurements',{headers,data:{...entry,id:m.id,weight:80.9}})).ok()).toBeTruthy();
    expect((await request.put('/api/profile',{headers,data:{name:'Test',reason:'Vérifier le parcours.',target_weight:75,target_waist:85}})).ok()).toBeTruthy();
    const phaseResponse = await request.post('/api/phases',{headers,data:{title:'Phase test',kind:'Maintien',start_date:'2026-10-01',end_date:'2026-10-31',goal:'Vérifier',review:''}});
    expect(phaseResponse.status()).toBe(201); phaseId = (await phaseResponse.json()).id;
    const snapshot = await (await request.get('/api/tracker')).json();
    expect(snapshot.measurements.find((row: {id:string}) => row.id === m.id).weight).toBe(80.9);
    expect(snapshot.phases.find((row: {id:string}) => row.id === phaseId).start_date).toBe('2026-10-01');
    expect((await request.post('/api/backup',{headers,data:{version:1,...snapshot}})).ok()).toBeTruthy();
    const invalid = {version:1,...snapshot,measurements:[...snapshot.measurements,{...entry,id:'bad-uuid'}]};
    expect((await request.post('/api/backup',{headers,data:invalid})).status()).toBe(400);
    const after = await (await request.get('/api/tracker')).json();
    expect(after.measurements.length).toBe(snapshot.measurements.length);
  } finally {
    for (const id of createdIds) await request.delete('/api/measurements',{headers,data:{id}});
    if (phaseId) await request.delete('/api/phases',{headers,data:{id:phaseId}});
    await request.put('/api/profile',{headers,data:original.profile});
  }
});
test('new measurements and personal goals persist, edit, complete, export and restore on mobile', async ({ page, request, baseURL }) => {
  const headers = { Origin: baseURL! };
  let measurementId: string | undefined;
  let goalId: string | undefined;
  const source = `Mensurations test ${Date.now()}`;
  const title = `Petits pas ${Date.now()}`;
  try {
    await page.setViewportSize({width:390,height:844});
    await page.goto('/');
    await page.locator('.page-heading').getByRole('button',{name:'Ajouter une mesure',exact:true}).click();
    let modal = page.getByRole('dialog');
    await modal.getByLabel('Poids (kg)').fill('80');
    for (const [label,value] of [['Tour de poitrine (cm)','100'],['Tour de hanches (cm)','98'],['Tour de bras (cm)','32'],['Tour de cuisse (cm)','55'],['Tour de mollet (cm)','37']]) await modal.getByLabel(label).fill(value);
    await modal.getByLabel('Provenance des mesures').fill(source);
    await modal.getByRole('button',{name:'Enregistrer ma mesure'}).click();
    await expect(modal).not.toBeVisible();
    let snapshot = await (await request.get('/api/tracker')).json();
    measurementId = snapshot.measurements.find((m: {source:string}) => m.source === source)?.id;
    expect(measurementId).toBeTruthy();
    await page.reload();
    await page.getByRole('button',{name:'Voir le graphique : Tour de bras',exact:true}).click();
    await expect(page.getByLabel('Indicateur du graphique')).toHaveValue('arm');
    await expect(page.getByRole('img',{name:/Évolution.*32.*cm/})).toBeVisible();
    await page.getByRole('button',{name:'Journal de mesures',exact:true}).click();
    const row = page.getByRole('row').filter({hasText:source});
    await expect(row).toContainText('100');
    await row.getByRole('button',{name:/Modifier la mesure/}).click();
    modal = page.getByRole('dialog');
    await expect(modal.getByLabel('Tour de bras (cm)')).toHaveValue('32');
    await modal.getByLabel('Tour de bras (cm)').fill('32.5');
    await modal.getByLabel('Tour de mollet (cm)').fill('');
    await modal.getByRole('button',{name:'Enregistrer ma mesure'}).click();
    await expect(modal).not.toBeVisible();
    await page.getByRole('button',{name:'Ma motivation',exact:true}).click();
    await page.getByRole('button',{name:'Nouvel objectif',exact:true}).click();
    modal = page.getByRole('dialog');
    await modal.getByLabel('Nom de l’objectif').fill(title);
    await modal.getByLabel('Ce que cela représente pour moi').fill('Retrouver mon rythme.');
    await modal.getByLabel('Cible à atteindre').fill('4');
    await modal.getByLabel('Progression actuelle').fill('1');
    await modal.getByLabel('Unité',{exact:true}).fill('séances');
    await modal.getByLabel('Échéance (facultative)').fill('2026-12-31');
    await modal.getByRole('button',{name:'Enregistrer mon objectif'}).click();
    await expect(modal).not.toBeVisible();
    snapshot = await (await request.get('/api/tracker')).json();
    goalId = snapshot.goals.find((g: {title:string}) => g.title === title)?.id;
    expect(goalId).toBeTruthy();
    await page.reload();
    await page.getByRole('button',{name:'Ma motivation',exact:true}).click();
    const article = page.getByRole('article').filter({hasText:title});
    await expect(article.getByRole('progressbar')).toHaveAttribute('aria-valuenow','25');
    await article.getByRole('button',{name:'Modifier / progresser'}).click();
    await page.getByRole('dialog').getByLabel('Progression actuelle').fill('2');
    await page.getByRole('dialog').getByRole('button',{name:'Enregistrer mon objectif'}).click();
    await expect(article.getByRole('progressbar')).toHaveAttribute('aria-valuenow','50');
    await article.getByRole('button',{name:`Accomplir ${title}`,exact:true}).click();
    await expect(article.getByRole('progressbar')).toHaveAttribute('aria-valuenow','100');
    await expect(article.getByText('Accompli',{exact:true})).toBeVisible();
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy();
    await page.screenshot({path:'test-results/objectifs-mobile.png',fullPage:true});
    await page.getByRole('button',{name:'Objectifs & données',exact:true}).click();
    const downloadEvent = page.waitForEvent('download');
    await page.getByRole('button',{name:'Exporter ma sauvegarde',exact:true}).click();
    const download = await downloadEvent;
    const backup = JSON.parse(await readFile((await download.path())!,'utf8'));
    expect(backup.version).toBe(2);
    expect(backup.measurements.find((m: {id:string}) => m.id === measurementId)).toMatchObject({chest:100,hips:98,arm:32.5,thigh:55,calf:null});
    expect(backup.goals.find((g: {id:string}) => g.id === goalId)).toMatchObject({target:4,current:4,unit:'séances',deadline:'2026-12-31'});
    // Legacy backups do not erase unrelated personal goals.
    expect((await request.post('/api/backup',{headers,data:{version:1,profile:backup.profile,measurements:[],phases:[]}})).ok()).toBeTruthy();
    expect((await request.post('/api/goals',{headers,data:{title:'Invalid',description:'',target:0,current:0,unit:'fois',deadline:null}})).status()).toBe(400);
    await request.delete('/api/measurements',{headers,data:{id:measurementId}});
    await request.delete('/api/goals',{headers,data:{id:goalId}});
    page.once('dialog',dialog => dialog.accept());
    await page.getByLabel('Fichier de sauvegarde JSON').setInputFiles({name:'forma.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(backup))});
    await expect(page.getByRole('status')).toContainText('Sauvegarde importée.');
    snapshot = await (await request.get('/api/tracker')).json();
    expect(snapshot.measurements.find((m: {id:string}) => m.id === measurementId).arm).toBe(32.5);
    expect(snapshot.goals.find((g: {id:string}) => g.id === goalId).current).toBe(4);
    await page.getByRole('button',{name:'Ma motivation',exact:true}).click();
    page.once('dialog',dialog => dialog.accept());
    await article.getByRole('button',{name:`Supprimer l’objectif ${title}`,exact:true}).click();
    await expect(article).toHaveCount(0);
  } finally {
    if (measurementId) await request.delete('/api/measurements',{headers,data:{id:measurementId}});
    if (goalId) await request.delete('/api/goals',{headers,data:{id:goalId}});
  }
});
